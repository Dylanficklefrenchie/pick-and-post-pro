/* TALES FROM BELLAMERE COURT — episode list. Data: episodes.json (add an episode = append one entry:
   number, title, video, cover, captions[{label, main?, text}]). Brand page: /episodes/. Affiliate page: /affiliate/episodes/
   (generated by redeploy.sh: this same page + <base href="../../episodes/"> + the affiliate scripts). Video files are never altered. */
(function(){
  var $ = function(id){ return document.getElementById(id); };
  var P = window.PPP || null;                    /* present only in affiliate mode (affiliate-core.js) */
  function esc(s){ var d = document.createElement('div'); d.textContent = s; return d.innerHTML; }
  function finalCaption(text){ return P ? P.caption('episodes', text, P.getLink()) : text; }   /* affiliate: existing #ad + footer rule */
  function copy(text){
    if(P) return P.copyText(text);
    if(navigator.clipboard && navigator.clipboard.writeText) return navigator.clipboard.writeText(text);
    var ta = document.createElement('textarea'); ta.value = text; document.body.appendChild(ta); ta.select(); var ok = document.execCommand('copy'); document.body.removeChild(ta);
    return ok ? Promise.resolve() : Promise.reject();
  }
  if(P){
    document.documentElement.setAttribute('data-mode', 'affiliate');
    $('epBack').href = '../affiliate/picker/';
    var a = $('epAff'); a.classList.remove('hide');
    a.innerHTML = 'Affiliate captions start with <b>#ad</b> and end with your footer. Say <b>“link in bio”</b>. Please don’t add platform music, voiceovers or discount codes, and don’t edit the video.' +
      (P.getLink() ? '' : ' <br><b>No affiliate link saved yet</b> — <a href="../affiliate/">add your link</a> first.');
  }
  function card(ep){
    var c = document.createElement('section'); c.className = 'card ep-card';
    var file = ep.video.split('/').pop();
    var h = '<p class="ep-num">Episode ' + ep.number + '</p><p class="name ep-title">' + esc(ep.title) + '</p>' +
      '<video class="ep-video" controls playsinline preload="none" poster="' + esc(ep.cover) + '" src="' + esc(ep.video) + '"></video>' +
      '<div class="ep-row"><a class="btn small" href="' + esc(ep.video) + '" download="' + esc(file) + '" type="video/mp4">Save video</a></div>';
    var caps = ep.captions.slice().sort(function(x, y){ return (y.main ? 1 : 0) - (x.main ? 1 : 0); });
    caps.forEach(function(cp, i){
      h += '<div class="ep-cap"><h3>Caption ' + (i + 1) + ' · ' + esc(cp.label) + (cp.main ? '<small>MAIN</small>' : '') + '</h3>' +
        '<pre>' + esc(finalCaption(cp.text)) + '</pre><button type="button" class="btn small" data-cap="' + i + '">Copy caption ' + (i + 1) + '</button><p class="msg" role="status"></p></div>';
    });
    c.innerHTML = h;
    c.querySelectorAll('[data-cap]').forEach(function(b){
      b.addEventListener('click', function(){
        var m = b.nextElementSibling, t = finalCaption(caps[+b.getAttribute('data-cap')].text);
        copy(t).then(function(){ m.classList.remove('err'); m.textContent = 'Caption copied ✓ Paste it into your Reel.'; },
                     function(){ m.classList.add('err'); m.textContent = 'Could not copy — press and hold the caption to copy it.'; });
      });
    });
    return c;
  }
  fetch('episodes.json', {cache: 'no-store'}).then(function(r){ return r.json(); }).then(function(list){
    var box = $('epList'); box.innerHTML = '';
    list.slice().sort(function(a, b){ return b.number - a.number; }).forEach(function(ep){ box.appendChild(card(ep)); });   /* newest first */
  }).catch(function(){ $('epList').innerHTML = '<p class="msg err">Could not load episodes.</p>'; });
})();
